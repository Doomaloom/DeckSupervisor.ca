import { mkdir, readFile, writeFile } from "node:fs/promises";

// Run from any directory; Rectab's extracted catalog is the source of truth.
const root = new URL("../../", import.meta.url);
const source = new URL(
    "../rec-tablet/internal/workflows/swimming/curriculum/catalog.json",
    root,
);
const catalog = JSON.parse(await readFile(source, "utf8"));
const compactTitles = JSON.parse(
    await readFile(
        new URL(
            "../rec-tablet/internal/workflows/swimming/curriculum/compact_titles.json",
            root,
        ),
        "utf8",
    ),
);
function defaultWorkoutText(skill) {
    if (!/\bworkouts?\b/i.test(skill.name)) return undefined;
    const sets = (skill.subskills || []).filter((subskill) =>
        /\d+\s*m\b/i.test(subskill.text) &&
        subskill.group.some((group) =>
            /warm[- ]?up|cool[- ]?down|work set|main set|stroke drills/i.test(group)
        )
    );
    if (sets.length) {
        let previousGroup = "";
        return sets.flatMap((set) => {
            const group = set.group.join(" / ").replace(/:$/, "");
            const lines = group === previousGroup
                ? [set.text]
                : [...(previousGroup ? [""] : []), `${group}:`, set.text];
            previousGroup = group;
            return lines;
        }).join("\n");
    }
    // Some curricula put the prescribed sets in the skill name.
    if (/\d+\s*m[;:]/i.test(skill.name)) {
        return skill.name.replace(/;\s*/g, "\n");
    }
    return undefined;
}
const levels = catalog.levels.map(({ id, name, skills }) => ({
    id,
    name,
    skills: skills.map((skill) => ({
        id: skill.id,
        name: skill.name,
        compactName: compactTitles[skill.id] || skill.name,
        defaultWorkoutText: defaultWorkoutText(skill),
    })),
}));
await writeFile(
    new URL("frontend/src/features/instructor/lessonSkills.json", root),
    JSON.stringify(levels, null, 4) + "\n",
);
const supported = levels.filter((level) => level.skills.length).map((level) =>
    level.id
);
await mkdir(new URL("backend/internal/curriculum/", root), { recursive: true });
await writeFile(
    new URL("backend/internal/curriculum/levels.json", root),
    JSON.stringify(supported, null, 2) + "\n",
);
await writeFile(
    new URL("backend/supabase_lesson_plan_curriculum.sql", root),
    `-- Generated by frontend/scripts/generate-lesson-skills.mjs from Rectab catalog.json.
-- Apply after supabase_lesson_plans.sql and before deploying the updated API.
begin;
alter table public.instructor_plans add column if not exists curriculum_level text;
alter table public.instructor_plans drop constraint if exists instructor_plan_curriculum_level;
alter table public.instructor_plans add constraint instructor_plan_curriculum_level
 check (curriculum_level is null or curriculum_level in (${
        supported.map((id) => "'" + id + "'").join(", ")
    }));
commit;
`,
);
