#!/usr/bin/env python3
"""Refresh immutable result criterion IDs from reviewed Rectab catalogs.
Usage: python3 scripts/generate-result-curriculum.py [--migration OUT.sql] CATALOG.json [CATALOG.json ...]
Every catalog gets a frozen insert block in backend/supabase_results_sync.sql (list older versions first;
old rows must stay so old records keep validating). With --migration, the LAST catalog's rows are also
written as a standalone idempotent insert-only file (no begin/commit) for applying to an existing database.
Benchmark timing limits in result_validate must also track benchmarks.go.
"""
import json
from pathlib import Path
import sys

MARK = '-- Frozen curriculum IDs, generated from rec-tablet catalog '
args = sys.argv[1:]
migration = None
if args and args[0] == '--migration':
    migration, args = Path(args[1]), args[2:]
if not args:
    sys.exit(__doc__)

def rows(catalog):
    out = ''
    for level in catalog['levels']:
        for skill in level['skills']:
            values = [catalog['version'], level['id'], skill['id'], json.dumps([s['id'] for s in skill['subskills']])]
            out += 'insert into public.result_curriculum values(' + ','.join("'" + v.replace("'", "''") + "'" for v in values) + ') on conflict do nothing;\n'
    return out

catalogs = [json.loads(Path(a).read_text()) for a in args]
versions = [c['version'] for c in catalogs]
if len(set(versions)) != len(versions):
    sys.exit('duplicate catalog versions: ' + ', '.join(versions))
path = Path(__file__).resolve().parent.parent / 'backend/supabase_results_sync.sql'
content = path.read_text().split(MARK)[0]
for catalog in catalogs:
    content += MARK + catalog['version'] + '.\n' + rows(catalog)
path.write_text(content + 'commit;\n')
print('wrote', path, {c['version']: rows(c).count('\n') for c in catalogs})
if migration:
    last = catalogs[-1]
    migration.parent.mkdir(parents=True, exist_ok=True)
    migration.write_text('-- Insert-only, idempotent: result_curriculum rows for catalog ' + last['version'] + '.\n'
                         '-- Adds rows only; existing versions and result data are untouched. Generated by scripts/generate-result-curriculum.py.\n' + rows(last))
    print('wrote', migration)
